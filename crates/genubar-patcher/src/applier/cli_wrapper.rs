use super::StatefulStepApplier;
use crate::utils::paths::{expand_tokens, home_dir};
use genubar_core::MenuError;
use genubar_platform::fs_utils::{read_text_file, remove_file_if_exists, write_executable_file};
use std::collections::BTreeMap;
use std::path::Path;

pub(crate) struct CliWrapperApplier<'a> {
    pub binary_name: &'a str,
    pub target_binary_path: &'a str,
    pub inject_env: &'a BTreeMap<String, String>,
    pub append_args: &'a [String],
}

impl StatefulStepApplier for CliWrapperApplier<'_> {
    fn resource_key(&self) -> (String, String) {
        (
            format!("cli_wrapper:{}", self.binary_name),
            format!("env={:?};args={:?}", self.inject_env, self.append_args),
        )
    }

    fn apply_change(&self, _patch_id: &str) -> Result<Option<String>, MenuError> {
        apply(
            self.binary_name,
            self.target_binary_path,
            self.inject_env,
            self.append_args,
        )
    }

    fn revert_change(
        &self,
        _patch_id: &str,
        orig_opt: Option<String>,
        _force_unsafe: bool,
    ) -> Result<(), MenuError> {
        revert(self.binary_name, orig_opt)
    }
}

pub fn apply(
    binary_name: &str,
    target_binary_path: &str,
    inject_env: &BTreeMap<String, String>,
    append_args: &[String],
) -> Result<Option<String>, MenuError> {
    let resolved_target = expand_tokens(target_binary_path);
    if !Path::new(&resolved_target).exists() {
        return Err(MenuError::NotFound(format!(
            "Target binary '{resolved_target}' does not exist"
        )));
    }

    let wrapper_path = home_dir().join(".local/bin").join(binary_name);
    let orig_content = if wrapper_path.is_file() {
        Some(read_text_file(&wrapper_path)?)
    } else {
        None
    };

    let script_body = build_wrapper_script(&resolved_target, inject_env, append_args);
    write_executable_file(&wrapper_path, &script_body)?;
    Ok(orig_content)
}

pub fn revert(binary_name: &str, orig_opt: Option<String>) -> Result<(), MenuError> {
    let wrapper_path = home_dir().join(".local/bin").join(binary_name);
    match orig_opt {
        Some(prev_content) => write_executable_file(&wrapper_path, &prev_content),
        None => remove_file_if_exists(&wrapper_path),
    }
}

fn build_wrapper_script(
    target_bin: &str,
    inject_env: &BTreeMap<String, String>,
    append_args: &[String],
) -> String {
    let mut env_exports = String::new();
    for (k, v) in inject_env {
        let expanded_val = expand_tokens(v);
        env_exports.push_str(&format!("export {k}=\"{expanded_val}\"\n"));
    }

    let args_str = if append_args.is_empty() {
        String::new()
    } else {
        let expanded: Vec<String> = append_args.iter().map(|a| expand_tokens(a)).collect();
        format!(" {}", expanded.join(" "))
    };

    format!("#!/usr/bin/env sh\n# Generated by Genubar Patcher\n{env_exports}exec \"{target_bin}\"{args_str} \"$@\"\n")
}